export function syntaxLanguage(id) {
  return syntaxLanguages.find(lang => lang.id === id) || syntaxLanguages.find(lang => lang.id === 'javascript')
}

export function editorLanguage(lang) {
  return lang.id === 'markup' ? 'html' : lang.id
}
