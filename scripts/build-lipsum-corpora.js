import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lipsumDir = join(root, 'src/assets/lipsums')
const outFile = join(root, 'src/lipsumCorpora.js')

const labels = {
  childharold: 'Childe Harold',
  decameron: 'Decameron',
  faust: 'Faust',
  inderfremde: 'In der Fremde',
  lebateauivre: 'Le Bateau ivre',
  lemasque: 'Le Masque',
  loremipsum: 'Lorem ipsum',
  nagyonfaj: 'Nagyon fáj',
  omagyar: 'Ómagyar',
  robinsonokruso: 'Robinsono Kruso',
  theraven: 'The Raven',
  tierrayluna: 'Tierra y Luna',
}

function textFromXml(raw) {
  const match = raw.match(/<text>([\s\S]*?)<\/text>/i)
  return match ? match[1].replace(/\s+/g, ' ').trim() : ''
}

const corpora = {}
for (const name of readdirSync(lipsumDir).filter(f => f.endsWith('.xml')).sort()) {
  const id = name.replace(/\.xml$/, '')
  corpora[id] = { label: labels[id] || id, text: textFromXml(readFileSync(join(lipsumDir, name), 'utf8')) }
}

const body = `// Generated by scripts/build-lipsum-corpora.js — NLipsum / DevToys lipsum texts (public domain).\nexport const lipsumCorpora = ${JSON.stringify(corpora, null, 2)}\nexport const lipsumCorpusIds = ${JSON.stringify(Object.keys(corpora))}\n`
writeFileSync(outFile, body)
